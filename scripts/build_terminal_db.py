#!/usr/bin/env python
"""Build the database the Phase 2 terminal runs against.

Real SEC data, clearly labelled synthetic market data
------------------------------------------------------
Fundamentals come from the archived SEC payloads under ``fixtures/`` for four issuers
(Apple, Microsoft, Walmart, Alphabet): filings, filing history and XBRL facts, ingested
offline through the same code path as a live sync.

Atlas has no licensed market-data feed. Rather than ship fake "quotes" pretending to
be observed prices, this script generates a **deterministic synthetic OHLCV series**
per security, registers it under its own source (``synthetic-demo``, kind
``synthetic``), and the terminal labels it SYNTHETIC everywhere it appears. The series
is internally consistent (OHLC invariants, trading-calendar sessions only, one Apple
4:1 split and quarterly dividends) so charting, adjustment, total-return and indicator
paths are exercised with real arithmetic on explicitly non-real prices.

Replace it by importing your own licensed data with ``atlas bars import``; nothing in
the terminal assumes synthetic data exists.

Usage:
    python scripts/build_terminal_db.py [--db var/atlas.db] [--force]
"""

from __future__ import annotations

import argparse
import json
import random
import sys
from datetime import date, timedelta
from decimal import Decimal
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from atlas.core.temporal import availability_from_instant  # noqa: E402
from atlas.entities.master import SecurityMaster  # noqa: E402
from atlas.ingestion.sec_history import load_fixture_history  # noqa: E402
from atlas.ingestion.sec_sync import (  # noqa: E402
    SecIngestor,
    load_fixture_payloads,
    register_fixture_documents,
)
from atlas.market.actions import ActionStore, ActionType, CorporateAction  # noqa: E402
from atlas.market.bars import Bar, BarStore  # noqa: E402
from atlas.market.calendar import TradingCalendar  # noqa: E402
from atlas.storage.db import Database  # noqa: E402
from atlas.storage.sources import SourceRegistry, ensure_default_sources  # noqa: E402
from atlas.terminal.store import SettingsStore  # noqa: E402

ISSUERS = (
    {"name": "Apple", "cik": "0000320193", "fixture": "fixtures/sec", "seed": 11, "price": 54.0, "volume": 8_000_000},
    {"name": "Microsoft", "cik": "0000789019", "fixture": "fixtures/sec_msft", "seed": 23, "price": 180.0, "volume": 3_500_000},
    {"name": "Walmart", "cik": "0000104169", "fixture": "fixtures/sec_wmt", "seed": 37, "price": 120.0, "volume": 2_500_000},
    {"name": "Alphabet", "cik": "0001652044", "fixture": "fixtures/sec_googl", "seed": 53, "price": 75.0, "volume": 4_000_000},
    # IBM exercises the provider-shaped market path: SEC fundamentals plus the
    # project-authored synthetic fixture in fixtures/market/ (no vendor archive is
    # tracked; a user with a licensed feed imports their own file).
    {"name": "IBM", "cik": "0000051143", "fixture": "fixtures/sec_ibm", "seed": 0,
     "price": 0.0, "volume": 0, "market": "synthetic_fixture"},
)

START = "2019-01-02"
END = "2024-12-31"
MIC = "XNAS"
SYNTHETIC_SOURCE = "synthetic-demo"


def register_synthetic_source(db: Database) -> str:
    return SourceRegistry(db).ensure_custom(
        "Atlas synthetic demonstration series",
        kind="synthetic",
        licence="Apache-2.0 (generated by Atlas for demonstration)",
        redistribution="project_authored",
        notes=(
            "Deterministic OHLCV generated for the Phase 2 terminal demonstration. "
            "Not observed market data and not suitable for investment decisions."
        ),
        source_id=SYNTHETIC_SOURCE,
    )


def ingest_sec(db: Database) -> list[dict]:
    ingestor = SecIngestor(db)
    master = SecurityMaster(db)
    results = []
    for spec in ISSUERS:
        fixture = ROOT / spec["fixture"]
        submissions, facts, _, _ = load_fixture_payloads(fixture, spec["cik"])
        submissions_doc, facts_doc = register_fixture_documents(db, fixture, spec["cik"])
        history = load_fixture_history(fixture, spec["cik"])
        report = ingestor.sync_payloads(
            spec["cik"],
            submissions_payload=submissions,
            companyfacts_payload=facts,
            submissions_doc_id=submissions_doc,
            companyfacts_doc_id=facts_doc,
            history_documents=history,
        )
        issuer = master.require_issuer_by_cik(spec["cik"])
        results.append(
            {
                "name": spec["name"],
                "issuer_id": issuer["issuer_id"],
                "filings": report.filings_written,
                "evidence": report.evidence.get("inserted", 0),
                "history_archives": len(history),
                "history_complete": (report.history or {}).get("coverage", {}).get("complete"),
            }
        )
        print(f"  {spec['name']}: {report.filings_written} filings, "
              f"{report.evidence.get('inserted', 0)} facts, {len(history)} archive(s)", flush=True)
    return results


def _sessions(db: Database) -> list[str]:
    calendar = TradingCalendar(db)
    calendar.ensure_venue(MIC)
    calendar.ensure_range(MIC, START, END)
    return calendar.session_dates(MIC, START, END)


def generate_series(seed: int, start_price: float, base_volume: int, sessions: list[str]) -> list[dict]:
    """Deterministic random walk; returns raw (pre-adjustment) OHLCV rows."""
    rng = random.Random(seed)
    price = start_price
    rows = []
    for index, day in enumerate(sessions):
        gap = rng.gauss(0.0002, 0.004)
        ret = rng.gauss(0.00045, 0.013)
        open_price = max(1.0, price * (1.0 + gap))
        close = max(1.0, open_price * (1.0 + ret))
        high = max(open_price, close) * (1.0 + abs(rng.gauss(0.0, 0.004)))
        low = min(open_price, close) * (1.0 - abs(rng.gauss(0.0, 0.004)))
        volume = int(base_volume * (0.55 + rng.random() * 0.9))
        rows.append(
            {
                "date": day,
                "open": round(open_price, 2),
                "high": round(max(high, open_price, close), 2),
                "low": round(min(low, open_price, close), 2),
                "close": round(close, 2),
                "volume": volume,
            }
        )
        price = close
    return rows


def ingest_market(db: Database) -> dict:
    master = SecurityMaster(db)
    bars = BarStore(db)
    actions = ActionStore(db)
    sessions = _sessions(db)
    source_id = register_synthetic_source(db)
    inserted = 0
    action_count = 0
    for spec in ISSUERS:
        if spec.get("market") == "synthetic_fixture":
            continue  # the fixture series is ingested by ingest_fixture_market
        issuer = master.require_issuer_by_cik(spec["cik"])
        securities = master.securities_for_issuer(issuer["issuer_id"])
        if not securities:
            continue
        for position, security in enumerate(securities):
            security_id = security["security_id"]
            if db.query_one("SELECT 1 FROM bar WHERE security_id = ? LIMIT 1", (security_id,)):
                continue
            # Give every share class a distinct, deterministic path.
            rows = generate_series(spec["seed"] + position * 101, spec["price"], spec["volume"], sessions)
            if spec["name"] == "Apple" and position == 0:
                # A real 4:1 split on 2020-08-28, applied as a raw price jump so the
                # adjustment engine has a genuine discontinuity to correct.
                split_date = "2020-08-28"
                for row in rows:
                    if row["date"] >= split_date:
                        for key in ("open", "high", "low", "close"):
                            row[key] = round(row[key] / 4.0, 2)
                actions.add(
                    CorporateAction(
                        security_id=security_id,
                        action_type=ActionType.SPLIT.value,
                        source_id=source_id,
                        ex_date=split_date,
                        ratio_from=Decimal("1"),
                        ratio_to=Decimal("4"),
                        notes="Synthetic demonstration of a 4:1 split (not an exchange record).",
                    ),
                    availability=availability_from_instant(f"{split_date}T12:00:00Z", "synthetic.generated"),
                )
                action_count += 1
            for year in range(2019, 2025):
                for month, day in ((3, 14), (6, 13), (9, 12), (12, 12)):
                    ex_date = date(year, month, day)
                    if ex_date < date(2019, 1, 2) or ex_date > date(2024, 12, 20):
                        continue
                    if spec["name"] == "Apple" and position == 0 and ex_date < date(2020, 8, 28):
                        amount = Decimal("0.82")
                    else:
                        amount = Decimal("0.25")
                    actions.add(
                        CorporateAction(
                            security_id=security_id,
                            action_type=ActionType.CASH_DIVIDEND.value,
                            source_id=source_id,
                            ex_date=ex_date.isoformat(),
                            cash_amount=amount,
                            currency="USD",
                            notes="Synthetic quarterly dividend for demonstration; not a declared dividend.",
                        ),
                        availability=availability_from_instant(f"{ex_date.isoformat()}T12:00:00Z", "synthetic.generated"),
                    )
                    action_count += 1
            payload = [
                Bar(
                    security_id=security_id,
                    mic=MIC,
                    ts_utc=f"{row['date']}T20:00:00Z",
                    open=Decimal(str(row["open"])),
                    high=Decimal(str(row["high"])),
                    low=Decimal(str(row["low"])),
                    close=Decimal(str(row["close"])),
                    volume=Decimal(str(row["volume"])),
                    currency=security.get("currency") or "USD",
                    source_id=source_id,
                    observed_at=f"{row['date']}T21:00:00Z",
                )
                for row in rows
            ]
            summary = bars.ingest(payload)
            inserted += summary.to_dict().get("inserted", 0)
    return {
        "bars_inserted": inserted,
        "actions": action_count,
        "sessions": len(sessions),
        "source_id": source_id,
        "notice": "SYNTHETIC market data - not observed prices",
    }


def ingest_fixture_market(db: Database) -> dict:
    """Ingest the distributable synthetic market fixture for IBM.

    This runs the provider-shaped parsing, ingestion and corporate-action paths on values
    Atlas authored. It is labelled SYNTHETIC everywhere and carries no vendor terms,
    because a repository may not redistribute a vendor's price history.
    """
    from atlas.ingestion.market_alphavantage import load_synthetic_fixture

    master = SecurityMaster(db)
    issuer = master.require_issuer_by_cik("0000051143")
    securities = master.securities_for_issuer(issuer["issuer_id"])
    if not securities:
        raise SystemExit("IBM issuer has no security; SEC ingestion failed")
    security = securities[0]
    listings = master.listings(security["security_id"])
    if not listings:
        raise SystemExit("IBM security has no listing; cannot attach market observations")
    primary = next((item for item in listings if item.get("is_primary")), listings[0])
    mic = str(primary["mic"])
    source_id = register_synthetic_source(db)
    payload = load_synthetic_fixture(
        ROOT / "fixtures" / "market",
        security_id=security["security_id"],
        mic=mic,
        source_id=source_id,
    )
    observed_at = "2024-12-13T21:00:00Z"
    for bar in payload["bars"]:
        bar.observed_at = observed_at
    summary = BarStore(db).ingest(payload["bars"], observed_at=observed_at)
    actions = ActionStore(db)
    action_count = 0
    for action in payload["actions"]:
        ex_date = action.ex_date or "2024-12-13"
        actions.add(
            action,
            availability=availability_from_instant(
                f"{ex_date}T21:00:00Z", "synthetic.generated"
            ),
        )
        action_count += 1
    return {
        "bars": summary.to_dict(),
        "actions": action_count,
        "source_id": source_id,
        "mic": mic,
        "ticker": (payload["meta"] or {}).get("2. Symbol"),
        "synthetic": True,
        "notice": "SYNTHETIC market fixture - generated values, not observed prices",
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--db", default=str(ROOT / "var" / "atlas.db"))
    parser.add_argument("--force", action="store_true", help="replace an existing database")
    args = parser.parse_args()

    path = Path(args.db)
    if path.exists():
        if not args.force:
            print(f"database already exists: {path} (use --force to rebuild)", file=sys.stderr)
            return 1
        for suffix in ("", "-wal", "-shm"):
            candidate = Path(str(path) + suffix)
            if candidate.exists():
                candidate.unlink()
    path.parent.mkdir(parents=True, exist_ok=True)

    db = Database(path)
    applied = db.migrate()
    ensure_default_sources(db)
    print(f"building {path} (schema v{db.schema_version()}, applied {applied or 'no'} migration(s))", flush=True)
    issuers = ingest_sec(db)
    market = ingest_market(db)
    fixture_market = ingest_fixture_market(db)
    settings = SettingsStore(db)
    settings.set("theme", "dark")
    settings.set("mode", "standard")
    summary = {
        "database": str(path),
        "schema_version": db.schema_version(),
        "issuers": issuers,
        "evidence_total": int(db.scalar("SELECT COUNT(*) FROM evidence", default=0) or 0),
        "filings_total": int(db.scalar("SELECT COUNT(*) FROM filing", default=0) or 0),
        "market": market,
        "fixture_market": fixture_market,
    }
    print(json.dumps(summary, indent=2))
    db.close()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
