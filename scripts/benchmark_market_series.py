"""Measure the canonical market contract on deterministic synthetic databases.

Phase 9.2.6 measured selection on a 10-row fixture, which says nothing about a realistic
market workload. This script generates reproducible databases at several sizes — two
providers, revisions and provider conflicts included — and measures the canonical paths
against the bare row lookup they replaced.

    python scripts/benchmark_market_series.py --tiers 100,1000 \
        --out artifacts/phase9_2_7_benchmark.json

Nothing here is a market simulation: every price is generated from an index, so the
numbers are latencies, not financial results. The databases are written to a temporary
directory and deleted unless ``--keep`` is passed; no large fixture is committed.
"""

from __future__ import annotations

import argparse
import json
import shutil
import statistics
import sys
import tempfile
import time
import tracemalloc
from datetime import date, timedelta
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT / "src") not in sys.path:
    sys.path.insert(0, str(ROOT / "src"))

from atlas.core.temporal import iso, utcnow  # noqa: E402
from atlas.entities.master import SecurityMaster  # noqa: E402
from atlas.market import evidence  # noqa: E402
from atlas.market.bars import BarStore  # noqa: E402
from atlas.storage.db import Database  # noqa: E402
from atlas.storage.sources import ensure_default_sources  # noqa: E402
from atlas.terminal import read_models  # noqa: E402

PRIMARY_SOURCE = "atlas-synthetic"
SECONDARY_SOURCE = "bench-vendor-b"


class CountingDatabase(Database):
    """Database that counts statement executions, so query cost is measured, not guessed."""

    def __init__(self, *args, **kwargs) -> None:
        super().__init__(*args, **kwargs)
        self.statements = 0

    def reset(self) -> None:
        self.statements = 0

    def query(self, sql, params=()):  # type: ignore[override]
        self.statements += 1
        return super().query(sql, params)

    def query_one(self, sql, params=()):  # type: ignore[override]
        self.statements += 1
        return super().query_one(sql, params)

    def execute(self, sql, params=()):  # type: ignore[override]
        self.statements += 1
        return super().execute(sql, params)


def business_days(count: int, end: str = "2024-12-31") -> list[str]:
    day, out = date.fromisoformat(end), []
    while len(out) < count:
        if day.weekday() < 5:
            out.append(day.isoformat())
        day -= timedelta(days=1)
    return sorted(out)


def build_database(path: Path, securities: int, sessions: int, *, providers: int = 2) -> dict:
    db = CountingDatabase(path)
    db.migrate()
    ensure_default_sources(db)
    db.execute(
        "INSERT OR IGNORE INTO source (source_id, name, kind, homepage, licence, redistribution, notes, created_at) "
        "VALUES (?,?,?,?,?,?,?,?)",
        (
            SECONDARY_SOURCE,
            "Benchmark second vendor",
            "vendor",
            None,
            "Synthetic benchmark data",
            "restricted",
            "Generated by scripts/benchmark_market_series.py; not real market data.",
            iso(utcnow()),
        ),
    )
    days = business_days(sessions)
    master = SecurityMaster(db)
    master.ensure_venue("XNYS", "New York Stock Exchange", country="US", timezone="America/New_York")
    with db.transaction():
        for index in range(securities):
            issuer = master.register_issuer(
                legal_name=f"Benchmark Issuer {index:05d}", cik=f"{3000000 + index}"
            )
            security = master.ensure_security(issuer, class_designation="common stock", currency="USD")
            listing = master.ensure_listing(security, "XNYS", valid_from="2000-01-01", is_primary=True)
            master.assign_ticker(
                listing,
                f"B{index:05d}",
                valid_from="2000-01-01",
                confidence=1.0,
                status="confirmed",
                source_id=PRIMARY_SOURCE,
            )

    sql = (
        "INSERT INTO bar (security_id, mic, interval, ts_utc, revision_seq, open, high, low, close, volume, "
        "trades, vwap, currency, adjustment_status, source_id, observed_at, ingested_at, supersedes_bar, "
        "quality_flags) VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)"
    )
    observed = iso(utcnow())
    rows = []
    ids = [row["security_id"] for row in db.query("SELECT security_id FROM security ORDER BY security_id")]
    for position, security_id in enumerate(ids):
        base = 50.0 + position * 0.25
        for offset, day in enumerate(days):
            close = base * (1 + ((offset % 17) - 8) / 1000)
            for source in (PRIMARY_SOURCE,) + ((SECONDARY_SOURCE,) if providers > 1 and position % 10 == 0 else ()):
                price = close + (0.75 if source == SECONDARY_SOURCE else 0.0)
                revision = 1
                rows.append(
                    (
                        security_id, "XNYS", "1d", f"{day}T21:00:00Z", revision,
                        price - 0.2, price + 0.3, price - 0.4, price, 1_000_000,
                        None, None, "USD", "raw", source, observed, observed, None, None,
                    )
                )
                # A provider correction on one session for every twentieth security.
                if position % 20 == 0 and offset == len(days) // 2:
                    rows.append(
                        (
                            security_id, "XNYS", "1d", f"{day}T21:00:00Z", 2,
                            price - 0.1, price + 0.35, price - 0.3, price + 0.1, 1_100_000,
                            None, None, "USD", "raw", source, observed, observed, 1, None,
                        )
                    )
    with db.transaction():
        db.executemany(sql, rows)
    return {"database": db, "securities": ids, "sessions": len(days), "rows": len(rows)}


def _percentile(values: list[float], fraction: float) -> float:
    ordered = sorted(values)
    index = min(len(ordered) - 1, max(0, int(round(fraction * (len(ordered) - 1)))))
    return ordered[index]


def measure(fn, *, repeats: int) -> dict:
    samples = []
    for _ in range(repeats):
        start = time.perf_counter()
        fn()
        samples.append((time.perf_counter() - start) * 1000)
    return {
        "runs": len(samples),
        "median_ms": round(statistics.median(samples), 3),
        "p95_ms": round(_percentile(samples, 0.95), 3),
        "min_ms": round(min(samples), 3),
        "max_ms": round(max(samples), 3),
    }


def benchmark_tier(directory: Path, securities: int, sessions: int) -> dict:
    path = directory / f"bench-{securities}.db"
    built = build_database(path, securities, sessions)
    db: CountingDatabase = built["database"]
    ids = built["securities"]
    sample = [ids[i] for i in range(0, len(ids), max(1, len(ids) // 20))][:20]
    store = BarStore(db)

    def canonical(security_id: str) -> None:
        evidence.select_price(db, security_id, "2999-12-31", mic="XNYS")

    def row_lookup(security_id: str) -> None:
        store.latest_close(security_id, "XNYS", "2999-12-31")

    def full_series(security_id: str) -> None:
        evidence.select_series(db, security_id, mic="XNYS", start="2023-12-01", end="2024-12-31")

    selection_samples: list[float] = []
    row_samples: list[float] = []
    series_samples: list[float] = []
    for security_id in sample:
        for _ in range(5):
            start = time.perf_counter(); canonical(security_id)
            selection_samples.append((time.perf_counter() - start) * 1000)
            start = time.perf_counter(); row_lookup(security_id)
            row_samples.append((time.perf_counter() - start) * 1000)
        start = time.perf_counter(); full_series(security_id)
        series_samples.append((time.perf_counter() - start) * 1000)

    db.reset()
    start = time.perf_counter()
    overview = read_models.market_overview(db)
    cold_ms = (time.perf_counter() - start) * 1000
    overview_statements = db.statements

    db.reset()
    start = time.perf_counter()
    read_models.market_overview(db)
    warm_ms = (time.perf_counter() - start) * 1000

    tracemalloc.start()
    read_models.market_overview(db)
    _, peak = tracemalloc.get_traced_memory()
    tracemalloc.stop()

    db.reset()
    start = time.perf_counter()
    read_models.market_series(db, ids[0], range_key="1Y")
    chart_ms = (time.perf_counter() - start) * 1000
    chart_statements = db.statements

    conflicts = db.scalar(
        "SELECT COUNT(*) FROM (SELECT security_id, ts_utc, COUNT(DISTINCT source_id) AS n "
        "FROM bar GROUP BY security_id, ts_utc HAVING n > 1)"
    )
    size = path.stat().st_size
    db.close()
    return {
        "securities": securities,
        "sessions": built["sessions"],
        "bar_rows": built["rows"],
        "database_bytes": size,
        "conflicting_sessions": int(conflicts or 0),
        "overview_items": overview["count"],
        "latest_close_query": {
            "median_ms": round(statistics.median(row_samples), 3),
            "p95_ms": round(_percentile(row_samples, 0.95), 3),
        },
        "canonical_select_price": {
            "median_ms": round(statistics.median(selection_samples), 3),
            "p95_ms": round(_percentile(selection_samples, 0.95), 3),
        },
        "canonical_series_1y": {
            "median_ms": round(statistics.median(series_samples), 3),
            "p95_ms": round(_percentile(series_samples, 0.95), 3),
        },
        "chart_1y": {"ms": round(chart_ms, 3), "statements": chart_statements},
        "overview": {
            "cold_ms": round(cold_ms, 3),
            "warm_ms": round(warm_ms, 3),
            "statements": overview_statements,
            "statements_per_item": round(overview_statements / max(1, overview["count"]), 2),
            "peak_tracemalloc_bytes": peak,
        },
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--tiers", default="100,1000", help="comma-separated security counts")
    parser.add_argument("--sessions", type=int, default=260, help="stored sessions per security")
    parser.add_argument("--out", default="artifacts/phase9_2_7_benchmark.json")
    parser.add_argument("--keep", action="store_true", help="keep the generated databases")
    args = parser.parse_args()

    tiers = [int(value) for value in args.tiers.split(",") if value.strip()]
    directory = Path(tempfile.mkdtemp(prefix="atlas-bench-"))
    results = {
        "schema": "atlas.market_benchmark.v1",
        "generated_at": iso(utcnow()),
        "python": sys.version.split()[0],
        "note": (
            "Synthetic prices generated by index; latencies only. Two providers on every tenth "
            "security and a revision on one session of every twentieth create real conflicts."
        ),
        "tiers": [],
    }
    try:
        for tier in tiers:
            print(f"building tier {tier} securities x {args.sessions} sessions ...", flush=True)
            results["tiers"].append(benchmark_tier(directory, tier, args.sessions))
            print(json.dumps(results["tiers"][-1], indent=2), flush=True)
    finally:
        if not args.keep:
            shutil.rmtree(directory, ignore_errors=True)
        else:
            results["database_directory"] = str(directory)

    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(results, indent=2) + "\n")
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
