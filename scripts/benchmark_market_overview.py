"""Measure the Markets overview before and after the Phase 9.2.8 bulk projection.

Phase 9.2.7 measured the overview at 666 ms for 100 securities and 7,585 ms for 1,000,
with about 24 statements per security. Those numbers are reproduced here by running the
preserved scalar path (``read_models.market_overview_scalar``) side by side with the
set-based projection (``atlas.terminal.market_projection``), on the same database, in the
same process, with the same cutoff.

    python scripts/benchmark_market_overview.py --tiers 100,1000 --out artifacts/phase9_2_8_market_overview.json

What is measured per tier:

* cold latency (first call in the process), warm latency (median and p95 over repeats);
* executed SQL statements, counted at the single ``execute`` primitive, so a statement is
  counted once (the older counter wrapped ``query``/``query_one``/``execute``, each of
  which reaches ``execute``, and therefore reported every statement twice);
* peak traced Python memory of the bulk plan;
* database bytes, stored bar rows, conflicting sessions, revised sessions;
* correctness parity: the two plans must return the same document, compared exactly.

Prices are generated from an index. These are latencies and query plans, not market
results, and the databases live in a temporary directory (kept only with ``--keep``).
"""

from __future__ import annotations

import argparse
import json
import platform
import shutil
import sqlite3
import statistics
import sys
import tempfile
import time
import tracemalloc
from datetime import date, timedelta
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT / "src") not in sys.path:
    sys.path.insert(0, str(ROOT / "src"))

from atlas.core.temporal import iso, utcnow  # noqa: E402
from atlas.entities.master import SecurityMaster  # noqa: E402
from atlas.storage.db import Database  # noqa: E402
from atlas.storage.sources import ensure_default_sources  # noqa: E402
from atlas.terminal import market_projection, read_models  # noqa: E402

PRIMARY_SOURCE = "atlas-synthetic"
SECONDARY_SOURCE = "bench-vendor-b"
END_SESSION = "2024-12-31"
CUTOFF = END_SESSION


class CountingDatabase(Database):
    """Counts statements at the one primitive every read path reaches."""

    def __init__(self, *args, **kwargs) -> None:
        super().__init__(*args, **kwargs)
        self.statements = 0

    def reset(self) -> None:
        self.statements = 0

    def execute(self, sql, params=()):  # type: ignore[override]
        self.statements += 1
        return super().execute(sql, params)


def business_days(count: int, end: str = END_SESSION) -> list[str]:
    day, out = date.fromisoformat(end), []
    while len(out) < count:
        if day.weekday() < 5:
            out.append(day.isoformat())
        day -= timedelta(days=1)
    return sorted(out)


def build_database(path: Path, securities: int, sessions: int, *, providers: int = 2) -> dict:
    db = CountingDatabase(path)
    db.migrate()
    ensure_default_sources(db)
    db.execute(
        "INSERT OR IGNORE INTO source (source_id, name, kind, homepage, licence, redistribution, notes, created_at) "
        "VALUES (?,?,?,?,?,?,?,?)",
        (
            SECONDARY_SOURCE,
            "Benchmark second vendor",
            "market_data",
            None,
            "Synthetic benchmark data",
            "restricted",
            "Generated by scripts/benchmark_market_overview.py; not real market data.",
            iso(utcnow()),
        ),
    )
    days = business_days(sessions)
    master = SecurityMaster(db)
    master.ensure_venue("XNYS", "New York Stock Exchange", country="US", timezone="America/New_York")
    with db.transaction():
        for index in range(securities):
            issuer = master.register_issuer(
                legal_name=f"Benchmark Issuer {index:05d}", cik=f"{3000000 + index}"
            )
            security = master.ensure_security(issuer, class_designation="common stock", currency="USD")
            listing = master.ensure_listing(security, "XNYS", valid_from="2000-01-01", is_primary=True)
            master.assign_ticker(
                listing,
                f"B{index:05d}",
                valid_from="2000-01-01",
                confidence=1.0,
                status="confirmed",
                source_id=PRIMARY_SOURCE,
            )

    sql = (
        "INSERT INTO bar (security_id, mic, interval, ts_utc, revision_seq, open, high, low, close, volume, "
        "trades, vwap, currency, adjustment_status, source_id, observed_at, ingested_at, supersedes_bar, "
        "quality_flags) VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)"
    )
    observed = iso(utcnow())
    rows = []
    ids = [row["security_id"] for row in db.query("SELECT security_id FROM security ORDER BY security_id")]
    conflicting_sessions = 0
    revised_sessions = 0
    for position, security_id in enumerate(ids):
        base = 50.0 + position * 0.25
        for offset, day in enumerate(days):
            close = base * (1 + ((offset % 17) - 8) / 1000)
            for source in (PRIMARY_SOURCE,) + (
                (SECONDARY_SOURCE,) if providers > 1 and position % 10 == 0 else ()
            ):
                price = close + (0.75 if source == SECONDARY_SOURCE else 0.0)
                rows.append(
                    (
                        security_id, "XNYS", "1d", f"{day}T21:00:00Z", 1,
                        price - 0.2, price + 0.3, price - 0.4, price, 1_000_000,
                        None, None, "USD", "raw", source, observed, observed, None, None,
                    )
                )
                if source == SECONDARY_SOURCE:
                    conflicting_sessions += 1
                if position % 20 == 0 and offset == len(days) // 2:
                    rows.append(
                        (
                            security_id, "XNYS", "1d", f"{day}T21:00:00Z", 2,
                            price - 0.1, price + 0.35, price - 0.3, price + 0.1, 1_100_000,
                            None, None, "USD", "raw", source, observed, observed, 1, None,
                        )
                    )
                    revised_sessions += 1
    with db.transaction():
        db.executemany(sql, rows)
    db.checkpoint()
    return {
        "database": db,
        "securities": ids,
        "sessions": len(days),
        "rows": len(rows),
        "conflicting_sessions": conflicting_sessions,
        "revised_sessions": revised_sessions,
    }


def _percentile(values: list[float], fraction: float) -> float:
    ordered = sorted(values)
    index = min(len(ordered) - 1, max(0, int(round(fraction * (len(ordered) - 1)))))
    return ordered[index]


def _timed(fn, repeats: int) -> dict:
    samples = []
    for _ in range(repeats):
        started = time.perf_counter()
        fn()
        samples.append((time.perf_counter() - started) * 1000)
    return {
        "runs": len(samples),
        "median_ms": round(statistics.median(samples), 2),
        "p95_ms": round(_percentile(samples, 0.95), 2),
        "min_ms": round(min(samples), 2),
        "max_ms": round(max(samples), 2),
    }


def benchmark_tier(directory: Path, securities: int, sessions: int, *, repeats: int) -> dict:
    path = directory / f"overview-{securities}.db"
    built = build_database(path, securities, sessions)
    db: CountingDatabase = built["database"]

    # Cold: first call in this process for each plan.
    db.reset()
    started = time.perf_counter()
    scalar_first = read_models.market_overview(db, projection="scalar", as_of=CUTOFF)
    scalar_cold_ms = (time.perf_counter() - started) * 1000
    scalar_statements = db.statements

    db.reset()
    started = time.perf_counter()
    bulk_first = read_models.market_overview(db, projection="bulk", as_of=CUTOFF)
    bulk_cold_ms = (time.perf_counter() - started) * 1000
    bulk_statements = db.statements

    scalar_warm = _timed(
        lambda: read_models.market_overview(db, projection="scalar", as_of=CUTOFF), repeats
    )
    bulk_warm = _timed(
        lambda: read_models.market_overview(db, projection="bulk", as_of=CUTOFF), repeats
    )

    tracemalloc.start()
    read_models.market_overview(db, projection="bulk", as_of=CUTOFF)
    _, bulk_peak = tracemalloc.get_traced_memory()
    tracemalloc.stop()

    tracemalloc.start()
    read_models.market_overview(db, projection="scalar", as_of=CUTOFF)
    _, scalar_peak = tracemalloc.get_traced_memory()
    tracemalloc.stop()

    scalar_doc = {k: v for k, v in scalar_first.items() if k != "as_of"}
    bulk_doc = {k: v for k, v in bulk_first.items() if k != "as_of"}
    parity = scalar_doc == bulk_doc
    first_mismatch = None
    if not parity:
        for index, (left, right) in enumerate(zip(scalar_doc["items"], bulk_doc["items"])):
            if left != right:
                first_mismatch = {
                    "index": index,
                    "security_id": left.get("security_id"),
                    "fields": [key for key in left if left[key] != right.get(key)],
                }
                break
        if first_mismatch is None:
            first_mismatch = {"items": [len(scalar_doc["items"]), len(bulk_doc["items"])]}

    size = path.stat().st_size
    integrity = db.integrity_check()
    db.close()
    return {
        "securities": securities,
        "sessions": built["sessions"],
        "bar_rows": built["rows"],
        "database_bytes": size,
        "conflicting_sessions": built["conflicting_sessions"],
        "revised_sessions": built["revised_sessions"],
        "overview_items": scalar_first["count"],
        "scalar": {
            "cold_ms": round(scalar_cold_ms, 2),
            "warm": scalar_warm,
            "statements": scalar_statements,
            "statements_per_item": round(scalar_statements / max(1, scalar_first["count"]), 2),
            "peak_tracemalloc_bytes": scalar_peak,
        },
        "bulk": {
            "cold_ms": round(bulk_cold_ms, 2),
            "warm": bulk_warm,
            "statements": bulk_statements,
            "statements_per_item": round(bulk_statements / max(1, scalar_first["count"]), 2),
            "peak_tracemalloc_bytes": bulk_peak,
            "projection_version": market_projection.PROJECTION_VERSION,
        },
        "speedup": {
            "cold_x": round(scalar_cold_ms / bulk_cold_ms, 2) if bulk_cold_ms else None,
            "warm_median_x": (
                round(scalar_warm["median_ms"] / bulk_warm["median_ms"], 2)
                if bulk_warm["median_ms"] else None
            ),
        },
        "statement_reduction_x": (
            round(scalar_statements / bulk_statements, 2) if bulk_statements else None
        ),
        "peak_memory_reduction_x": (
            round(scalar_peak / bulk_peak, 2) if bulk_peak else None
        ),
        "correctness_parity": parity,
        "first_mismatch": first_mismatch,
        "sqlite_integrity": integrity,
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--tiers", default="100,1000", help="comma-separated security counts")
    parser.add_argument("--sessions", type=int, default=260, help="stored sessions per security")
    parser.add_argument("--repeats", type=int, default=2, help="warm repetitions per plan")
    parser.add_argument("--out", default="artifacts/phase9_2_8_market_overview.json")
    parser.add_argument("--keep", action="store_true", help="keep the generated databases")
    args = parser.parse_args()

    tiers = [int(value) for value in args.tiers.split(",") if value.strip()]
    directory = Path(tempfile.mkdtemp(prefix="atlas-overview-bench-"))
    results = {
        "schema": "atlas.market_overview_benchmark.v1",
        "generated_at": iso(utcnow()),
        "cutoff": CUTOFF,
        "environment": {
            "python": sys.version.split()[0],
            "platform": platform.platform(),
            "cpu_count": None,
            "sqlite": sqlite3.sqlite_version,
        },
        "methodology": {
            "statements": (
                "counted at Database.execute, the single primitive every read path reaches; "
                "the Phase 9.2.7 counter wrapped query/query_one/execute and counted each "
                "statement twice"
            ),
            "cold": "first call in the process, after the database build",
            "warm": f"median and p95 of {args.repeats} consecutive calls in the same process",
            "memory": "peak traced Python allocation of one bulk overview (tracemalloc)",
            "parity": "the two plans must return the identical document, compared exactly",
        },
        "note": (
            "Synthetic prices generated from an index; two providers on every tenth security and "
            "one revision on every twentieth. Latencies and query plans only, not market results."
        ),
        "tiers": [],
    }
    try:
        import os

        results["environment"]["cpu_count"] = os.cpu_count()
        for tier in tiers:
            print(f"building {tier} securities x {args.sessions} sessions ...", flush=True)
            results["tiers"].append(benchmark_tier(directory, tier, args.sessions, repeats=args.repeats))
            print(json.dumps(results["tiers"][-1], indent=2), flush=True)
    finally:
        if not args.keep:
            shutil.rmtree(directory, ignore_errors=True)
        else:
            results["database_directory"] = str(directory)

    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(results, indent=2) + "\n")
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
