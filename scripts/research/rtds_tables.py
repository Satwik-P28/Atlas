"""Render the study's markdown tables from its JSON, so the paper cannot drift from the artifacts.

Run: ``.venv/bin/python scripts/research/rtds_tables.py``
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[2]
DATA = ROOT / "artifacts" / "research" / "rtds"


def pct(value: float | None, digits: int = 1) -> str:
    return "n/a" if value is None else f"{100 * value:.{digits}f}%"


def num(value: float | None, digits: int = 3) -> str:
    return "n/a" if value is None else f"{value:.{digits}f}"


def interval(block: dict[str, Any] | None) -> str:
    if not block or block.get("lower") is None:
        return "n/a"
    return f"[{100 * block['lower']:.1f}%, {100 * block['upper']:.1f}%]"


def main() -> None:
    results = json.loads((DATA / "results.json").read_text())
    dataset = json.loads((DATA / "dataset.json").read_text())
    lines = ["# Real-world revision study: generated tables", "",
             "Generated by `scripts/research/rtds_tables.py` from `results.json` and `dataset.json`.",
             "Do not hand-edit.", ""]

    lines += ["## Events by cohort and split", "",
              "| cohort | frequency | series | train | pilot | test | vintage files |",
              "|---|---|---|---|---|---|---|"]
    by_key = {cohort["cohort"]: cohort for cohort in results["cohorts"]}
    for cohort in dataset["cohorts"]:
        counts = by_key[cohort["cohort"]]["counts"]
        lines.append(f"| {cohort['cohort']} | {cohort['frequency']} | {', '.join(cohort['series'])} "
                     f"| {counts['train']} | {counts['pilot']} | {counts['test']} "
                     f"| {cohort['manifest_counts']['files']} |")
    lines.append("")

    lines += ["## Materiality of authentic revisions (test split)", "",
              "| cohort | τ | events | material | share (95% cluster interval) | median regret |",
              "|---|---|---|---|---|---|"]
    for cohort in results["cohorts"]:
        materiality = cohort["materiality"]
        rows = [row for row in cohort["rows"] if row["split"] == "test"]
        regrets = sorted(row["regret"] for row in rows)
        median = regrets[len(regrets) // 2] if regrets else None
        lines.append(f"| {cohort['cohort']} | {results['tau']:g} | {cohort['counts']['processed_test']} "
                     f"| {materiality['material_events']} "
                     f"| {pct(materiality['share'])} {interval(materiality['interval'])} "
                     f"| {num(median, 4)} |")
    lines.append("")

    lines += ["## Certification usefulness", "",
              "| cohort | certified immaterial | share (95% interval) | immaterial events with ‖Δc‖>0 "
              "| certified among them |",
              "|---|---|---|---|---|"]
    for cohort in results["cohorts"]:
        cert = cohort["certification"]
        lines.append(f"| {cohort['cohort']} | {pct(cert['share_certified_immaterial'])} "
                     f"| {interval(cert['interval'])} "
                     f"| {cert['immaterial_with_nonzero_revision']} "
                     f"| {pct(cert['certified_share_of_immaterial_nonzero'])} |")
    lines.append("")

    lines += ["## Methods, scored against re-solving (test split)", "",
              "| cohort | method | events scored | accuracy | false immaterial |",
              "|---|---|---|---|---|"]
    for cohort in results["cohorts"]:
        for name, block in cohort["methods"].items():
            if not block.get("events"):
                continue
            lines.append(f"| {cohort['cohort']} | {block['method']} | {block['events']} "
                         f"| {num(block['accuracy'])} | {block['false_immaterial']} |")
    lines.append("")

    lines += ["## Predictive power for materiality (fitted on train, scored on test)", "",
              "| cohort | ranking by ‖Δc‖ (AUC) | magnitude model | + revision metadata "
              "| + decision geometry | geometry interval |",
              "|---|---|---|---|---|---|"]
    for cohort in results["cohorts"]:
        p = cohort["prediction"]
        lines.append(f"| {cohort['cohort']} | {num(p['auc_magnitude_only'])} "
                     f"| {num(p['auc_magnitude_model'])} | {num(p['auc_metadata_model'])} "
                     f"| {num(p['auc_geometry_model'])} | {interval(p['auc_geometry_interval'])} |")
    lines.append("")

    lines += ["## Cost and information retained", "",
              "| cohort | certificate ms | OSQP ms | warm start ms | internal ms | "
              "audit record bytes | full problem bytes |",
              "|---|---|---|---|---|---|---|"]
    for cohort in results["cohorts"]:
        timing, storage = cohort["timing_ms"], cohort["storage"]
        lines.append(
            f"| {cohort['cohort']} | {num(timing['certificate_ms']['median'], 2)} "
            f"| {num(timing['external_ms']['median'], 2)} | {num(timing['warm_ms']['median'], 2)} "
            f"| {num(timing['internal_ms']['median'], 2)} "
            f"| {num(storage['audit_record_bytes']['median_bytes'], 0)} "
            f"| {num(storage['problem_bytes']['median_bytes'], 0)} |")
    lines.append("")

    lines += ["## Materiality by revision category (test split)", "",
              "| cohort | category | events | material |", "|---|---|---|---|"]
    for cohort in results["cohorts"]:
        for category, block in sorted(cohort["categories"].items()):
            lines.append(f"| {cohort['cohort']} | {category} | {block['events']} "
                         f"| {block['material']} |")
    lines.append("")

    lines += ["## Sensitivity to the risk weight and the materiality threshold", "",
              "| cohort | risk weight ρ | events | material at τ=1e-2 | at τ=1e-3 | at τ=1e-4 "
              "| certified at τ=1e-3 |",
              "|---|---|---|---|---|---|---|"]
    for key, grid in results["sensitivity"].items():
        for label, block in grid.items():
            materiality = block["materiality"]
            certified = block["certified_immaterial"]
            lines.append(f"| {key} | {label.split('=')[-1]} | {block['events']} "
                         f"| {pct(materiality['tau=0.01'])} | {pct(materiality['tau=0.001'])} "
                         f"| {pct(materiality['tau=0.0001'])} "
                         f"| {pct(certified['tau=0.001'])} |")
    lines.append("")
    (DATA / "tables.md").write_text("\n".join(lines))
    print(f"wrote {DATA / 'tables.md'}")


if __name__ == "__main__":
    main()
