import { Link } from 'react-router-dom'
import { api } from '../api'
import { useAsync } from '../state'
import { fmtCompact, fmtDate, fmtSignedPct, toneForNumber } from '../format'
import Sparkline from '../components/Sparkline'
import { Badge, DataStatusBadge, ErrorState, Loading, SectionHeader } from '../components/ui'

export default function Markets() {
  const { data, error, loading, reload } = useAsync(() => api.markets(), [])

  return (
    <div className="page">
      <SectionHeader
        eyebrow="Markets"
        title="Coverage overview"
        detail="Every security Atlas stores, with the last end-of-day observation and its source. Synthetic prices are labelled, never dressed up as a live quote."
        actions={data && <Badge tone={data.data_status === 'synthetic' ? 'synthetic' : 'accent'}>{data.count} securities</Badge>}
      />
      {loading && <Loading label="Loading market data" />}
      {error && <ErrorState error={error} onRetry={reload} />}
      {data && (
        <>
          {data.data_status === 'synthetic' && (
            <div className="banner banner-synthetic">
              <strong>SYNTHETIC price series.</strong> These OHLCV observations are generated by Atlas for
              demonstration (source <span className="mono">synthetic-demo</span>). They are not exchange data.
              Import licensed bars with <span className="mono">atlas bars import</span> to replace them.
            </div>
          )}
          <div className="table-wrap card">
            <table className="data-table markets-table">
              <thead>
                <tr>
                  <th>Ticker</th>
                  <th>Company</th>
                  <th className="numeric">Last</th>
                  <th className="numeric">1 day</th>
                  <th className="numeric">1 year</th>
                  <th>30 sessions</th>
                  <th className="numeric">Volume</th>
                  <th>Session</th>
                  <th>Source</th>
                </tr>
              </thead>
              <tbody>
                {data.items.map((item) => (
                  <tr key={item.security_id}>
                    <td>
                      <Link className="ticker-link mono" to={`/companies/${item.issuer_id}`}>
                        {item.ticker ?? '—'}
                      </Link>
                      <div className="muted small">{item.mic}</div>
                    </td>
                    <td>
                      <Link to={`/companies/${item.issuer_id}`} className="text-link">
                        {item.legal_name}
                      </Link>
                    </td>
                    <td className="numeric mono">{fmtCompact(item.last_close)}</td>
                    <td className={`numeric mono ${toneForNumber(item.change_1d)}`}>
                      {item.change_1d === null ? '—' : fmtSignedPct(item.change_1d)}
                    </td>
                    <td className={`numeric mono ${toneForNumber(item.change_1y)}`}>
                      {item.change_1y === null ? '—' : fmtSignedPct(item.change_1y)}
                    </td>
                    <td>
                      <Sparkline values={item.sparkline} positive={(item.change_1y ?? 0) >= 0} />
                    </td>
                    <td className="numeric mono">{item.volume === null ? '—' : fmtCompact(item.volume).replace('$', '')}</td>
                    <td className="mono small">{fmtDate(item.last_bar_date)}</td>
                    <td>
                      <DataStatusBadge status={item.data_status} source={item.data_status === 'reported' ? 'sec' : null} />
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
            <div className="table-foot">
              <span className="muted small">{data.notes.join(' ')}</span>
              <span className="muted small">as of {fmtDate(data.as_of)}</span>
            </div>
          </div>

          <div className="card-grid">
            {data.sources
              .filter((source) => source.kind !== 'csv_import')
              .map((source) => (
                <div className="source-card" key={source.source_id}>
                  <div className="eyebrow">{source.kind}</div>
                  <div className="source-name">{source.name}</div>
                  <p className="muted small">{source.licence ?? 'licence not recorded'}</p>
                  <Badge tone={source.kind === 'synthetic' ? 'synthetic' : 'accent'}>{source.redistribution}</Badge>
                </div>
              ))}
          </div>
        </>
      )}
    </div>
  )
}
