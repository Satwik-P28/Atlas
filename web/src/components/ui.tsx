import type { ReactNode } from 'react'

export function Badge({
  children,
  tone = 'neutral',
  title,
}: {
  children: ReactNode
  tone?: 'neutral' | 'positive' | 'negative' | 'warn' | 'accent' | 'synthetic'
  title?: string
}) {
  return (
    <span className={`badge badge-${tone}`} title={title}>
      {children}
    </span>
  )
}

export function DataStatusBadge({ status, source }: { status: string | null | undefined; source?: string | null }) {
  if (!status || status === 'no_data') return <Badge tone="neutral">no market data</Badge>
  if (status === 'synthetic') {
    return (
      <Badge tone="synthetic" title="Generated by Atlas for demonstration. Not observed market prices.">
        SYNTHETIC
      </Badge>
    )
  }
  if (status === 'reported') {
    return <Badge tone="accent" title={source ?? 'Source-reported observation'}>{source ?? 'reported'}</Badge>
  }
  if (status === 'imported') return <Badge tone="accent">imported{source ? ` · ${source}` : ''}</Badge>
  return <Badge tone="neutral">{status}</Badge>
}

export function Loading({ label = 'Loading' }: { label?: string }) {
  return (
    <div className="state-block" role="status">
      <span className="spinner" aria-hidden />
      {label}…
    </div>
  )
}

export function ErrorState({ error, onRetry }: { error: Error; onRetry?: () => void }) {
  const code = (error as Error & { code?: string }).code
  return (
    <div className="state-block state-error" role="alert">
      <div>
        <div className="state-title">{code === 'database_missing' ? 'No database yet' : 'Could not load this view'}</div>
        <p className="muted">{error.message}</p>
        {code === 'database_missing' && (
          <p className="mono small">python scripts/build_terminal_db.py</p>
        )}
      </div>
      {onRetry && (
        <button className="button" onClick={onRetry}>
          Retry
        </button>
      )}
    </div>
  )
}

export function EmptyState({ title, detail }: { title: string; detail?: string }) {
  return (
    <div className="state-block">
      <div>
        <div className="state-title">{title}</div>
        {detail && <p className="muted">{detail}</p>}
      </div>
    </div>
  )
}

export function SectionHeader({
  eyebrow,
  title,
  detail,
  actions,
}: {
  eyebrow?: string
  title: string
  detail?: string
  actions?: ReactNode
}) {
  return (
    <div className="section-header">
      <div>
        {eyebrow && <div className="eyebrow">{eyebrow}</div>}
        <h2>{title}</h2>
        {detail && <p className="muted section-detail">{detail}</p>}
      </div>
      {actions && <div className="section-actions">{actions}</div>}
    </div>
  )
}
